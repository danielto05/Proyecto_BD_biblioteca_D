ALTER TABLE "prestamo" ADD FOREIGN KEY ("id_usuario_lector") REFERENCES "cuenta" ("id_usuario") DEFERRABLE INITIALLY IMMEDIATE;
 
ALTER TABLE "prestamo" ADD FOREIGN KEY ("id_usuario_registra") REFERENCES "cuenta" ("id_usuario") DEFERRABLE INITIALLY IMMEDIATE;
 
ALTER TABLE "prestamo" ADD FOREIGN KEY ("id_ejemplar") REFERENCES "ejemplar" ("id_ejemplar") DEFERRABLE INITIALLY IMMEDIATE;
 
ALTER TABLE "devolucion" ADD FOREIGN KEY ("id_usuario_registra") REFERENCES "cuenta" ("id_usuario") DEFERRABLE INITIALLY IMMEDIATE;
 
