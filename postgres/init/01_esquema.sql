-- 01_esquema.sql: esquema de la biblioteca (Hito 2)
-- Se ejecuta solo, una vez, cuando la base se crea vacia. pgcrypto se crea en public (antes de borrar el esquema) para no perderlo con el DROP CREATE EXTENSION IF NOT EXISTS pgcrypto; DROP SCHEMA IF EXISTS biblioteca CASCADE; CREATE SCHEMA biblioteca; SET search_path TO biblioteca, public; CREATE TABLE "rol" ( "id_rol" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "nombre" varchar UNIQUE NOT NULL, "descripcion" varchar); CREATE TABLE "cuenta" ( "id_usuario" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "id_rol" integer NOT NULL, "id_usuario_creador" integer, "usuario" varchar UNIQUE NOT NULL, "documento" varchar UNIQUE NOT NULL, "contrasena" varchar NOT NULL, "nombres" varchar NOT NULL, "apellidos" varchar NOT NULL, "correo" varchar NOT NULL, "telefono" varchar NOT NULL, "fecha_creacion" timestamp NOT NULL DEFAULT (now()), "activa" boolean NOT NULL DEFAULT true); CREATE TABLE "categoria" ( "id_categoria" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "nombre" varchar UNIQUE NOT NULL, "descripcion" varchar);
CREATE TABLE "libro" (
  "id_libro" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_categoria" integer NOT NULL,
  "isbn" varchar UNIQUE NOT NULL,
  "titulo" varchar NOT NULL,
  "autor" varchar NOT NULL,
  "editorial" varchar,
  "anio_publicacion" integer NOT NULL,
  "activo" boolean NOT NULL DEFAULT true
);
 
CREATE TABLE "ejemplar" (
  "id_ejemplar" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_libro" integer NOT NULL,
  "codigo" varchar UNIQUE NOT NULL,
  "estado" varchar NOT NULL
);
 
CREATE TABLE "prestamo" (
  "id_prestamo" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_usuario_lector" integer NOT NULL,
  "id_usuario_registra" integer NOT NULL,
  "id_ejemplar" integer NOT NULL,
  "fecha_prestamo" date NOT NULL,
  "fecha_limite" date NOT NULL,
  "estado" varchar NOT NULL
);
 
CREATE TABLE "devolucion" (
  "id_devolucion" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_prestamo" integer UNIQUE NOT NULL,
  "id_usuario_registra" integer NOT NULL,
  "fecha_devolucion" date NOT NULL,
  "estado_ejemplar" varchar NOT NULL
);
 
CREATE TABLE "notificacion_demora" (
  "id_notificacion" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_prestamo" integer NOT NULL,
  "fecha_envio" timestamp NOT NULL,
  "mensaje" varchar NOT NULL
);
 
ALTER TABLE "cuenta" ADD FOREIGN KEY ("id_rol") REFERENCES "rol" ("id_rol") DEFERRABLE INITIALLY IMMEDIATE;
 
ALTER TABLE "cuenta" ADD FOREIGN KEY ("id_usuario_creador") REFERENCES "cuenta" ("id_usuario") DEFERRABLE INITIALLY IMMEDIATE;
 
ALTER TABLE "libro" ADD FOREIGN KEY ("id_categoria") REFERENCES "categoria" ("id_categoria") DEFERRABLE INITIALLY IMMEDIATE;
 
